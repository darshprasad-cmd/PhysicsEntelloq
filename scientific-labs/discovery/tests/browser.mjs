import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium, expect } = require(process.env.PLAYWRIGHT_MODULE_PATH || '@playwright/test');
const root = fileURLToPath(new URL('../', import.meta.url));
const base = (process.env.DISCOVERY_TEST_URL || 'http://127.0.0.1:8000/').replace(/\/?$/, '/');
const output = process.env.QA_OUTPUT_DIR || root + 'verification';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
const errors = [];
const failedRequests = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  page.on('requestfailed', request => failedRequests.push({ url: request.url(), error: request.failure()?.errorText }));
  await page.goto(base);
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Evidence');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Desktop landing must not overflow.');
  await page.screenshot({ path: output + '/landing-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile landing must not overflow.');
  await page.screenshot({ path: output + '/landing-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const started = Date.now();
  await page.goto(base + 'notebook.html');
  await page.locator('.discovery-result').waitFor({ timeout: 180000 });
  await expect(page.getByRole('combobox')).toBeVisible({ timeout: 30000 });
  const initializationMs = Date.now() - started;
  const initial = await page.locator('.discovery-metric strong').first().textContent();
  await page.getByRole('slider').first().focus();
  await page.getByRole('slider').first().press('Home');
  await expect(page.locator('.discovery-metric strong').first()).toHaveText(/^1\.60/, { timeout: 30000 });
  const recomputed = await page.locator('.discovery-metric strong').first().textContent();
  assert.notEqual(initial, recomputed, 'Changing gravity must recompute the fitted synthetic result.');
  await page.getByRole('slider').first().blur();
  await page.screenshot({ path: output + '/notebook-pendulum.png', fullPage: true });
  await page.getByRole('combobox').selectOption({ label: 'Sampling · the missing motion' });
  await expect(page.getByRole('heading', { name: 'The samples do not tell the whole story.', exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.locator('.discovery-metric strong').nth(1)).toHaveText('3');
  await page.getByRole('slider').nth(1).focus();
  await page.getByRole('slider').nth(1).press('End');
  await expect(page.getByRole('heading', { name: 'Enough samples to resolve this frequency.', exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.locator('.discovery-metric strong').nth(1)).toHaveText('7');
  await page.getByRole('combobox').selectOption({ label: 'Projectile · fit a flight' });
  await expect(page.getByRole('heading', { name: 'Let the trajectory speak.', exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByRole('radio', { name: 'My CSV', exact: true }).check();
  await expect(page.locator('.discovery-error')).toContainText('Choose a projectile CSV');
  await page.locator('input[type=file]').setInputFiles(root + 'examples/synthetic-projectile.csv');
  await expect(page.locator('.discovery-metric strong').first()).toHaveText('9.810', { timeout: 30000 });
  await expect(page.locator('.discovery-result')).toContainText('User CSV: synthetic-projectile.csv');
  await page.getByRole('textbox', { name: /My prediction and interpretation/ }).fill('Synthetic verification: recovered the known constant gravity.');
  await page.getByRole('textbox', { name: /My prediction and interpretation/ }).blur();
  await page.waitForTimeout(800);
  const downloadEvent = page.waitForEvent('download');
  await page.getByText('Download investigation report', { exact: true }).click();
  const download = await downloadEvent;
  const stream = await download.createReadStream();
  const chunks = []; for await (const chunk of stream) chunks.push(chunk);
  const report = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  assert.equal(report.investigation, 'projectile');
  assert.equal(report.rows.length, 8);
  assert.ok(Math.abs(report.fit.gravity - 9.81) < 1e-8);
  assert.match(report.reflection, /recovered the known/);
  await page.locator('input[type=file]').setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from('time_s,x_m,y_m\n0,1,NaN\n1,2,3\n2,3,4\n3,4,5') });
  await expect(page.locator('.discovery-error')).toContainText('finite values', { timeout: 30000 });
  assert.equal(await page.locator('.discovery-result').count(), 0, 'Invalid CSV must not retain stale scientific results.');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('combobox').selectOption({ label: 'Sampling · the missing motion' });
  await expect(page.locator('.discovery-result')).toBeVisible({ timeout: 30000 });
  await page.screenshot({ path: output + '/notebook-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, 'Mobile notebook document must not overflow.');
  for (const slider of await page.getByRole('slider').all()) {
    const bounds = await slider.boundingBox();
    assert.ok(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 391, 'Mobile slider thumb must remain visible inside the viewport.');
  }
  const unexpected = errors.filter(error => error !== 'RPC request timed out.');
  assert.deepEqual(unexpected, [], 'No unexpected browser exceptions.');
  const result = { initializationMs, initial, recomputed, importedGravity: report.fit.gravity, importedRows: report.rows.length, reportDownloaded: true, invalidCsvRejected: true, mobileControlsWithinViewport: true, errors, failedRequests };
  await writeFile(output + '/qa.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
